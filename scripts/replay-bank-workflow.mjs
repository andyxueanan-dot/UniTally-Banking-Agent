import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { BankService } = require('../backend/bank/service');
const { createBankStore } = require('../backend/bank/store');
const evidence = path.resolve(import.meta.dirname, '../../evidence/T008-quality');
const original = JSON.parse(fs.readFileSync(path.join(evidence, 'model-baseline.json'))).cases.find(c => c.id === 'three-step');
const report = { classification: 'Offline replay of recorded model plan; NOT a new live-model success', liveCalls: 0, source: 'model-baseline.json / three-step', actions: original.actions };
const service = new BankService({ store: createBankStore(), planner: { configured: true, model: 'recorded-plan-replay', plan: async () => ({ actions: original.actions, question: '', meta: { mode: 'replay', totalTokens: 0 } }) } });
const { token } = service.create();
const response = await service.chat(token, { text: original.input });
const task = response.state.tasks.find(t => t.status === 'AWAITING_CONFIRMATION');
assert.equal(response.state.balance, 1286000);
const confirmed = service.confirm(token, task.id, { confirmed: true });
assert.equal(confirmed.state.balance, 1266000);
const advanced = service.workflowControl(token, confirmed.state.workflows[0].id, 'advance');
assert.equal(advanced.state.workflows[0].status, 'SUCCEEDED');
assert.equal(advanced.state.ledger.length, 1);
report.passed = true; report.workflowStatus = advanced.state.workflows[0].status;
fs.writeFileSync(path.join(evidence, 'workflow-replay.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
